import os as _os
HERE = _os.path.dirname(_os.path.abspath(__file__))
ROOT = _os.path.normpath(_os.path.join(HERE, '..', '..', '..'))
SCRIPTS = _os.path.join(ROOT, 'tools', 'scripts')
ENTRY = _os.path.join(ROOT, 'reference', 'snapshots', 'cyrus48-entry-6000.z80')
LVL1 = _os.path.join(ROOT, 'reference', 'snapshots', 'cyrus48-idle-level1.z80')
WORK = _os.path.join(HERE, 'work')
_os.makedirs(WORK, exist_ok=True)
import sys
sys.path.insert(0, HERE)
import chess
from compare import load, to88
from probe import Machine, SNAP, gen, sqname, call
from makeunmake import board_matches, VAL
from targeted import CASES
from skoolkit.simutils import SP, IXh, IXl

m = Machine(SNAP)
mem = m.memory
r = m.sim.registers
for fen, last, fl in CASES + [('4k3/1P6/8/8/8/8/8/4K3 w - - 0 1', None, 0), ('4k3/8/8/8/8/8/1p6/R3K3 b Q - 0 1', None, 0)]:
    b = chess.Board(fen)
    prev = (0, 0, fl)
    if last:
        mv = chess.Move.from_uci(last); prev = (to88(mv.from_square), to88(mv.to_square), fl)
    load(mem, b, prev)
    start, end, hdr, moves = gen(m, b.turn == chess.BLACK)
    for i, mvx in enumerate(moves):
        entry = start + 4 + 4 * i
        fr, to, flags = mvx[1:]
        pm = next((c for c in b.pseudo_legal_moves if to88(c.from_square) == fr and to88(c.to_square) == to and c.promotion in (None, chess.QUEEN)), None)
        if pm is None:
            pm = chess.Move(chess.square(fr & 7, fr >> 4), chess.square(to & 7, to >> 4))
            print(f'{fen.split()[0]} {pm.uci()} flags={flags:02X} generated by Cyrus but not pseudo-legal in python-chess (castling in/through check)')
            continue
        for score in ((0, 0xFF) if flags == 0x10 else (0,)):
            bb = list(mem[0xBD00:0xBD80]); pl = list(mem[0xBE00:0xBF00])
            mem[0xBD0D] = 0; mem[entry] = score
            sp0 = r[SP]
            r[IXh], r[IXl] = entry >> 8, entry & 0xFF
            call(m, 0x810F)
            nb = b.copy(); nb.push(pm)
            errs = board_matches(mem, nb) if b.is_legal(pm) else ['(illegal in chess)']
            kt = mem[0xBE80 + 1 if b.turn == chess.BLACK else 0xBE01]
            note = ''
            if flags == 0x10:
                rd = (fr + to) // 2
                note = f' score={score:02X} board[rookdest {sqname(rd)}]={mem[0xBD00 + rd]:02X} kingtype={kt:02X}'
            if pm.promotion or (b.piece_type_at(pm.from_square) == chess.PAWN):
                rec = 0xBE00 + (mem[0xBD00 + to] & 0xFB)
                note += f' pawntype={mem[rec + 1]:02X} flags->{mem[entry + 3]:02X} BD0D={mem[0xBD0D]:02X} stack={sp0 - r[SP]}'
            call(m, 0x821C)
            ok = list(mem[0xBD00:0xBD80]) == bb and list(mem[0xBE00:0xBF00]) == pl and r[SP] == sp0
            if errs or not ok or note:
                print(f'{fen.split()[0]} {pm.uci()} restored={ok} {errs}{note}')
